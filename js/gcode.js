// Reads filament use and print time from sliced files.
// G-code patterns follow Moonraker's metadata parser (Klipper's file manager):
// https://github.com/Arksine/moonraker/blob/master/moonraker/components/file_manager/metadata.py
// Bambu .gcode.3mf: Metadata/slice_info.config written by Bambu Studio
// (<metadata key="prediction"> seconds, <metadata key="weight"> grams, <filament used_g=…>).

const F = '([0-9]*\\.?[0-9]+)';
const floatsIn = (s) => (String(s).match(/[0-9]*\.?[0-9]+/g) || []).map(Number);
const sum = (a) => a.reduce((x, y) => x + y, 0);

export function parseDurationText(text) {
  let total = 0, found = false;
  for (const [re, mult] of [[/(\d+)\s*d/, 86400], [/(\d+)\s*h/, 3600], [/(\d+)\s*m(?!s)/, 60], [/(\d+)\s*s/, 1]]) {
    const m = text.match(re);
    if (m) { total += +m[1] * mult; found = true; }
  }
  return found ? total : null;
}

function identify(text) {
  let m = text.match(/; generated by (PrusaSlicer|SuperSlicer|OrcaSlicer|QIDISlicer|Slic3r[^ ]*) ([^\s]+)/);
  if (m) return `${m[1]} ${m[2]}`;
  m = text.match(/; BambuStudio[^ ]* ([^\n]+)/);
  if (m) return `Bambu Studio ${m[1].trim()}`;
  m = text.match(/Cura_SteamEngine\s([^\s]+)/);
  if (m) return `Cura ${m[1]}`;
  if (/Simplify3D\(R\)/.test(text)) return 'Simplify3D';
  if (/\sideaMaker\s/.test(text)) return 'ideaMaker';
  return null;
}

/**
 * Parses the start and end of a G-code file (slicers put their summary at one end or the other).
 * Returns { slicer, grams, lengthMm, seconds, filamentType } with null for anything not found.
 */
export function parseGcode(head, tail = '') {
  const text = `${head}\n${tail}`;
  const out = { slicer: identify(text), grams: null, lengthMm: null, seconds: null, filamentType: null };
  let m;

  // Bambu Studio
  if ((m = text.match(new RegExp(`; total filament weight \\[g\\] : ${F}`)))) out.grams = +m[1];
  if ((m = text.match(new RegExp(`; total filament length \\[mm\\] : ${F}`)))) out.lengthMm = +m[1];
  if ((m = text.match(/total estimated time:\s*([^;\n]+)/))) out.seconds = parseDurationText(m[1]);

  // PrusaSlicer / OrcaSlicer / SuperSlicer
  if (out.grams == null && (m = text.match(new RegExp(`total filament used \\[g\\] = ${F}`)))) out.grams = +m[1];
  if (out.grams == null && (m = text.match(/filament used \[g\] = ([^\n]+)/))) out.grams = sum(floatsIn(m[1]));
  if (out.lengthMm == null && (m = text.match(/filament used \[mm\] = ([^\n]+)/))) out.lengthMm = sum(floatsIn(m[1]));
  if (out.seconds == null && (m = text.match(/;\s*estimated printing time[^=\n]*=\s*([^\n]+)/))) out.seconds = parseDurationText(m[1]);

  // Cura
  if (out.seconds == null && (m = text.match(new RegExp(`;TIME:${F}`)))) out.seconds = +m[1];
  if (out.lengthMm == null && (m = text.match(/;Filament used:\s*([^\n]+)/))) out.lengthMm = sum(floatsIn(m[1])) * 1000; // metres
  if (out.grams == null && (m = text.match(/;Filament weight = \[([^\]]+)\]/))) out.grams = sum(floatsIn(m[1]));

  // Simplify3D
  if (out.lengthMm == null && (m = text.match(new RegExp(`;\\s+(?:Filament length|Material Length):\\s${F}\\smm`)))) out.lengthMm = +m[1];
  if (out.grams == null && (m = text.match(new RegExp(`;\\s+(?:Plastic weight|Material Weight):\\s${F}\\sg`)))) out.grams = +m[1];
  if (out.seconds == null && (m = text.match(/;\s+Build (?:t|T)ime:([^\n]+)/))) {
    const t = m[1];
    let s = 0;
    const hh = t.match(/(\d+)\shours?/), mm = t.match(/(\d+)\smin/), ss = t.match(/(\d+)\ssec/);
    if (hh || mm || ss) s = (hh ? +hh[1] * 3600 : 0) + (mm ? +mm[1] * 60 : 0) + (ss ? +ss[1] : 0);
    out.seconds = s || null;
  }

  // ideaMaker (length only)
  if (out.lengthMm == null) {
    const all = [...text.matchAll(new RegExp(`;Material.\\d\\sUsed:\\s+${F}`, 'g'))].map((x) => +x[1]);
    if (all.length) out.lengthMm = sum(all);
  }

  if ((m = text.match(/;\s*filament_type = ([^\n]+)/)) || (m = text.match(/;Filament type = ([^\n]+)/))) out.filamentType = m[1].split(/[;,]/)[0].trim();
  return out;
}

// ------------------------------------------------------------- 3MF (zip)

const u16 = (v, o) => v.getUint16(o, true);
const u32 = (v, o) => v.getUint32(o, true);

async function inflateRaw(bytes) {
  const stream = new Blob([bytes]).stream().pipeThrough(new DecompressionStream('deflate-raw'));
  return new Uint8Array(await new Response(stream).arrayBuffer());
}

/** Lists entries of a zip archive held in an ArrayBuffer. */
export function zipEntries(buf) {
  const v = new DataView(buf);
  let eocd = -1;
  for (let i = buf.byteLength - 22; i >= Math.max(0, buf.byteLength - 65557); i--) {
    if (u32(v, i) === 0x06054b50) { eocd = i; break; }
  }
  if (eocd < 0) throw new Error('not-zip');
  const count = u16(v, eocd + 10);
  let p = u32(v, eocd + 16);
  const dec = new TextDecoder();
  const entries = [];
  for (let i = 0; i < count; i++) {
    if (u32(v, p) !== 0x02014b50) break;
    const method = u16(v, p + 10), compSize = u32(v, p + 20), nameLen = u16(v, p + 28), extraLen = u16(v, p + 30), commentLen = u16(v, p + 32), local = u32(v, p + 42);
    const name = dec.decode(new Uint8Array(buf, p + 46, nameLen));
    entries.push({ name, method, compSize, local });
    p += 46 + nameLen + extraLen + commentLen;
  }
  return entries;
}

export async function readZipEntry(buf, entry) {
  const v = new DataView(buf);
  const p = entry.local;
  if (u32(v, p) !== 0x04034b50) throw new Error('bad-entry');
  const start = p + 30 + u16(v, p + 26) + u16(v, p + 28);
  const data = new Uint8Array(buf, start, entry.compSize);
  if (entry.method === 0) return data;
  if (entry.method === 8) return inflateRaw(data);
  throw new Error('unsupported-compression');
}

/** Parses a Bambu Studio / OrcaSlicer .gcode.3mf. Sums all plates in the file. */
export async function parse3mf(buf) {
  const entries = zipEntries(buf);
  const info = entries.find((e) => /^Metadata\/slice_info\.config$/i.test(e.name));
  const out = { slicer: 'Bambu Studio', grams: null, lengthMm: null, seconds: null, filamentType: null, plates: 0 };
  if (info) {
    const xml = new TextDecoder().decode(await readZipEntry(buf, info));
    const plates = xml.split(/<plate>/).slice(1);
    let g = 0, s = 0, m = 0, sawWeight = false, sawTime = false, sawLen = false;
    for (const plate of plates) {
      const w = plate.match(/key="weight"\s+value="([0-9.]+)"/);
      const t = plate.match(/key="prediction"\s+value="([0-9.]+)"/);
      const fil = [...plate.matchAll(/<filament\b[^>]*>/g)].map((x) => x[0]);
      const usedG = fil.map((f) => f.match(/used_g="([0-9.]+)"/)).filter(Boolean).map((x) => +x[1]);
      const usedM = fil.map((f) => f.match(/used_m="([0-9.]+)"/)).filter(Boolean).map((x) => +x[1]);
      if (w) { g += +w[1]; sawWeight = true; } else if (usedG.length) { g += sum(usedG); sawWeight = true; }
      if (usedM.length) { m += sum(usedM); sawLen = true; }
      if (t) { s += +t[1]; sawTime = true; }
      const type = fil.map((f) => f.match(/type="([^"]+)"/)).find(Boolean);
      if (type && !out.filamentType) out.filamentType = type[1];
    }
    out.plates = plates.length;
    if (sawWeight) out.grams = +g.toFixed(2);
    if (sawTime) out.seconds = s;
    if (sawLen) out.lengthMm = +(m * 1000).toFixed(1);
  }
  if (out.grams == null || out.seconds == null) {
    // Fall back to the embedded G-code header.
    const g = entries.find((e) => /^Metadata\/plate_\d+\.gcode$/i.test(e.name));
    if (g) {
      const bytes = await readZipEntry(buf, g);
      const dec = new TextDecoder();
      const head = dec.decode(bytes.subarray(0, 1 << 20));
      const tail = dec.decode(bytes.subarray(Math.max(0, bytes.length - (1 << 20))));
      const p = parseGcode(head, tail);
      out.grams ??= p.grams; out.seconds ??= p.seconds; out.lengthMm ??= p.lengthMm; out.filamentType ??= p.filamentType;
      if (p.slicer) out.slicer = p.slicer;
    }
  }
  return out;
}

/** Reads a File (browser) or Blob: .3mf whole, G-code by its first and last megabyte. */
export async function parseSlicedFile(file) {
  const name = (file.name || '').toLowerCase();
  if (name.endsWith('.3mf')) return parse3mf(await file.arrayBuffer());
  const MB = 1 << 20;
  const head = await file.slice(0, MB).text();
  const tail = file.size > MB ? await file.slice(Math.max(MB, file.size - MB)).text() : '';
  return parseGcode(head, tail);
}
